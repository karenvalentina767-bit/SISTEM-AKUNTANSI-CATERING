create table if not exists public.pelanggan (
  id bigint generated by default as identity primary key,
  nama_pelanggan text not null,
  no_hp text not null,
  email text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.pesanan_event (
  id bigint generated by default as identity primary key,
  pelanggan_id bigint not null references public.pelanggan(id) on delete cascade,
  nama_event text not null,
  tanggal_event date not null,
  jenis_paket text not null,
  jumlah_pax integer not null check (jumlah_pax > 0),
  harga_per_pax numeric(14, 2) not null check (harga_per_pax >= 0),
  total_penjualan numeric(14, 2) not null check (total_penjualan >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.pembayaran (
  id bigint generated by default as identity primary key,
  pesanan_id bigint not null references public.pesanan_event(id) on delete cascade,
  no_invoice text not null unique,
  tanggal_tagihan date not null,
  tanggal_tempo date not null,
  pajak_ppn numeric(14, 2) not null default 0,
  total_tagihan numeric(14, 2) not null check (total_tagihan >= 0),
  status_bayar text not null default 'Belum Lunas'
    check (status_bayar in ('Belum Lunas', 'Lunas')),
  created_at timestamptz not null default now()
);

alter table public.pelanggan disable row level security;
alter table public.pesanan_event disable row level security;
alter table public.pembayaran disable row level security;

create index if not exists pesanan_event_tanggal_idx on public.pesanan_event (tanggal_event);
create index if not exists pembayaran_status_idx on public.pembayaran (status_bayar);